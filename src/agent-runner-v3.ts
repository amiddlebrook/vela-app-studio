import { AGENT_RUNNER } from './agent-template';

const OLD_EXTRACT = [
  'function extractJson(text) {',
  "  const cleaned = String(text || '').trim().replace(/^\\x60\\x60\\x60(?:json)?\\s*/i, '').replace(/\\x60\\x60\\x60\\s*$/, '').trim();",
  '  try { return JSON.parse(cleaned); } catch {}',
  "  const first = cleaned.indexOf('{');",
  "  const last = cleaned.lastIndexOf('}');",
  '  if (first >= 0 && last > first) return JSON.parse(cleaned.slice(first, last + 1));',
  "  throw new Error('Model response was not valid JSON');",
  '}',
].join('\n');

const NEW_EXTRACT = [
  'function extractJson(text) {',
  "  const source = String(text || '').trim().replace(/^\\x60\\x60\\x60(?:json)?\\s*/i, '').replace(/\\x60\\x60\\x60\\s*$/, '').trim();",
  '  try { return JSON.parse(source); } catch {}',
  '  for (let start = 0; start < source.length; start++) {',
  "    const opener = source[start];",
  "    if (opener !== '{' && opener !== '[') continue;",
  "    const closer = opener === '{' ? '}' : ']';",
  '    let depth = 0;',
  '    let inString = false;',
  '    let escaped = false;',
  '    for (let i = start; i < source.length; i++) {',
  '      const ch = source[i];',
  '      if (inString) {',
  '        if (escaped) { escaped = false; continue; }',
  "        if (ch === '\\\\') { escaped = true; continue; }",
  "        if (ch === '\"') inString = false;",
  '        continue;',
  '      }',
  "      if (ch === '\"') { inString = true; continue; }",
  '      if (ch === opener) depth++;',
  '      else if (ch === closer) {',
  '        depth--;',
  '        if (depth === 0) {',
  '          const candidate = source.slice(start, i + 1);',
  '          try { return JSON.parse(candidate); } catch { break; }',
  '        }',
  '      }',
  '    }',
  '  }',
  "  throw new Error('Model response contained no complete valid JSON value');",
  '}',
].join('\n');

const OLD_POST = [
  'async function post(endpoint, body) {',
  '  const response = await fetch(controlPlane + endpoint, {',
  "    method: 'POST',",
  "    headers: { authorization: 'Bearer ' + token, 'content-type': 'application/json' },",
  '    body: JSON.stringify(Object.assign({ project_id: projectId, build_id: buildId }, body || {})),',
  '  });',
  '  const text = await response.text();',
  '  let payload = {};',
  '  try { payload = JSON.parse(text); } catch { payload = { error: text }; }',
  "  if (!response.ok) throw new Error(endpoint + ' failed (' + response.status + '): ' + String(payload.error || payload.reason || text).slice(0, 1000));",
  '  return payload;',
  '}',
].join('\n');

const NEW_POST = [
  'async function post(endpoint, body) {',
  '  const url = controlPlane + endpoint;',
  '  const requestBody = JSON.stringify(Object.assign({ project_id: projectId, build_id: buildId }, body || {}));',
  "  const attempts = endpoint === '/internal/agent/event' ? 2 : 4;",
  "  const timeoutMs = endpoint === '/internal/agent/llm' ? 90000 : 30000;",
  "  let last = 'unknown transport failure';",
  '  for (let attempt = 1; attempt <= attempts; attempt++) {',
  '    const controller = new AbortController();',
  '    const timer = setTimeout(() => controller.abort(), timeoutMs);',
  '    try {',
  '      const response = await fetch(url, {',
  "        method: 'POST',",
  "        headers: { authorization: 'Bearer ' + token, 'content-type': 'application/json' },",
  '        body: requestBody,',
  '        signal: controller.signal,',
  '      });',
  '      const text = await response.text();',
  '      let payload = {};',
  '      try { payload = JSON.parse(text); } catch { payload = { error: text }; }',
  '      if (response.ok) return payload;',
  "      last = endpoint + ' failed (' + response.status + '): ' + String(payload.error || payload.reason || text).slice(0, 1600);",
  '      if (response.status >= 400 && response.status < 500 && response.status !== 408 && response.status !== 409 && response.status !== 429) break;',
  '    } catch (error) {',
  "      const cause = error && error.cause ? ' | cause=' + String(error.cause) : '';",
  "      last = (error instanceof Error ? error.message : String(error)) + cause;",
  '    } finally { clearTimeout(timer); }',
  '    if (attempt < attempts) {',
  '      const wait = Math.min(1500 * (2 ** (attempt - 1)), 8000);',
  "      console.warn('[VELA_TRANSPORT_RETRY]', endpoint, 'attempt', attempt, last.slice(0, 700));",
  '      await new Promise(resolve => setTimeout(resolve, wait));',
  '    }',
  '  }',
  '  throw new Error(last);',
  '}',
].join('\n');

const patchedPost = AGENT_RUNNER.includes(OLD_POST) ? AGENT_RUNNER.replace(OLD_POST, NEW_POST) : AGENT_RUNNER;
export const AGENT_RUNNER_V3 = patchedPost.includes(OLD_EXTRACT) ? patchedPost.replace(OLD_EXTRACT, NEW_EXTRACT) : patchedPost;
